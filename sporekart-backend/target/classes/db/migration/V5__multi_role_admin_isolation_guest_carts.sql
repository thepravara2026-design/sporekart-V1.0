-- SPOREKART DATABASE MIGRATION V5: Multi-Role, Admin Isolation & Guest Carts
-- =============================================================================

-- 1. MULTI-ROLE MODEL FOR CUSTOMERS (BUYER & TRAINEE)
-- Drop existing single role column on users
ALTER TABLE users DROP COLUMN IF EXISTS role;

CREATE TABLE user_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role VARCHAR(50) NOT NULL CHECK (role IN ('BUYER', 'TRAINEE')),
    granted_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_roles_user_id_role UNIQUE(user_id, role)
);

-- 2. ISOLATED ADMIN IDENTITY SCHEMA
CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 3. GUEST CART PERSISTENCE
CREATE TABLE guest_carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_token VARCHAR(255) NOT NULL UNIQUE,
    items_json TEXT NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 4. GUEST ENROLLMENT INTENTS
CREATE TABLE training_enrollment_intents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guest_token VARCHAR(255) NOT NULL,
    batch_id BIGINT NOT NULL REFERENCES training_batches(id) ON DELETE CASCADE,
    target_input VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 5. OPTIMISTIC LOCKING ON PRODUCTS
ALTER TABLE products ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;
